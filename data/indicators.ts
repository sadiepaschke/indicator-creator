export const getIndicatorsBySector = (sector: string): Indicator[] =>
  indicators.filter(i => i.sector === sector);

export const searchIndicators = (query: string, sectorFilter?: string, levelFilter?: string): Indicator[] => {
  const lowerQuery = query.toLowerCase();
  return indicators.filter(i => {
    const matchesSearch = !query ||
      i.name.toLowerCase().includes(lowerQuery) ||
      i.definition.toLowerCase().includes(lowerQuery) ||
      i.tags.some(t => t.toLowerCase().includes(lowerQuery));
    const matchesSector = !sectorFilter || i.sector === sectorFilter;
    const matchesLevel = !levelFilter || i.level === levelFilter;
    return matchesSearch && matchesSector && matchesLevel;
  });
};
